from __future__ import annotations

from fastapi.responses import JSONResponse


def openai_error(message: str, status: int, code: str | None = None) -> JSONResponse:
    return JSONResponse(
        status_code=status,
        content={
            "error": {
                "message": message,
                "type": "invalid_request_error",
                "param": None,
                "code": code,
            }
        },
    )
